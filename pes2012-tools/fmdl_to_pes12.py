"""PES21 4cc fmdl -> PES2012 per-player custom body (drawlogic.dll format).

    python3 fmdl_to_pes12.py <body.fmdl> <texture.dds> <out_dir>

Writes <out_dir>/body.bin (vertices + indices) and <out_dir>/body.tex
(u32 'PGT1', w, h, mips, then BGRA8 mips largest first; decoded here by
PIL because uploading the DXT5 blocks through DXVK's d3d9 came out black).

Bones: the 19 main bones of the in-match body (dt09 #349 block 2,
rig/body349b2_bones.json, regenerated by pes12_rig.py from your game); BLENDINDICES are that body's palette slots, and
drawlogic uploads one matrix per slot at c20 + 3*slot itself.
Vertex format = the LOD0 kit's packet-5 declaration (dt0c #3, 755 verts/80 B,
grabbed 24-09): POSITION f3 | BLENDWEIGHT f3 | BLENDINDICES ubyte4 | NORMAL f3
| BINORMAL f3 | TANGENT f3 | TEXCOORD0 f2 | TEXCOORD1 f2 = 80 bytes.

Both games agree on basis: Y up, +Z forward, +X = the character's left
(PES12 thigh_l x=+0.09 like Fox sk_thigh_l; feet reach +z in both).

Pose: the fmdl is authored in Fox's RENDER bind (arms ~45 deg down); PES12's
bind is a T-pose. Each influence is re-posed rigidly about its bone:
    v12 = sum_b w_b * (P12(b) + W(b) (v - A(b)))
with A = Fox render-bind joint, W = retarget.PES_ALIGN (render -> anim pose,
identity on the trunk) and P12 = the PES12 joint the Fox bone maps to. The
per-bone translation also absorbs the proportion difference between the two
skeletons (PES12 hands at +-0.704 m, Fox anim hands at +-0.770 m).
"""
