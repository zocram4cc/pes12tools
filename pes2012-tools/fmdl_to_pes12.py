FINGER_SLOT = {'sk_hand_l': 19, 'sk_hand_r': 20}
FINGER_BONE = re.compile(r'skh_(index|middle|ring|pinky)_')


def slot_key(name, fox):
    """Influence key: the main bone, or (hand, finger group) for finger bones."""
    return (fox, True) if FINGER_BONE.match(name) and fox in FINGER_SLOT else (fox, False)


def key_slot(key, slot_of):
    fox, finger = key
    return FINGER_SLOT[fox] if finger else slot_of[FOX_TO_PES12[fox]]


def skin_pack(slot_w):
    """[(slot, weight), ...] heaviest first, summing to 1 -> (3 packed weights,
    4 blend indices) in the order PES2012's skin VS reads them: blend index 0
    takes the remainder 1 - (w0 + w1 + w2), index k + 1 takes w[k] (the kit and
    custom-body VS, disassembled 30-09). Packing the remainder onto the LAST
    index instead, as done since 24-09, rotated the weights of every vertex
    shared by two or more bones: creased knees and elbows, cuffs off the hands."""
    slots = [s for s, _ in slot_w]
    ws = [w for _, w in slot_w][1:]
    slots += [slots[0]] * (MAX_INFLUENCES - len(slots))
    ws += [0.0] * (MAX_INFLUENCES - 1 - len(ws))
    return ws, slots


def main_bone(name, fmdl_bind):
    """fmdl bone (helpers included) -> animated Fox bone it rigidly follows."""
    if name in FOX_TO_PES12:
        return name
    gf = retarget.resolve_bone(name, fmdl_bind)
    pes = PES_OF_GF.get(gf)
    if pes is None:
        raise KeyError('unmapped bone %s' % name)
    if pes.startswith('skh_'):  # fingers ride the hand in a 19-bone body
        pes = 'sk_hand_l' if pes.endswith('_l') else 'sk_hand_r'
    return pes


